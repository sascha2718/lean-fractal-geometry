#!/usr/bin/env python3
"""Check the consolidated source inventory, import closure and documentation.

This is a structural check. Lean compilation and FractalGeometry.AxCheck verify
proofs and their transitive axiom dependencies.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def lean_code(text: str) -> str:
    """Blank nested comments and strings, preserving line positions."""
    out = list(text)
    i, depth = 0, 0
    while i < len(text):
        if depth:
            if text.startswith('/-', i):
                depth += 1
                out[i:i + 2] = '  '
                i += 2
            elif text.startswith('-/', i):
                depth -= 1
                out[i:i + 2] = '  '
                i += 2
            else:
                if text[i] != '\n':
                    out[i] = ' '
                i += 1
        elif text.startswith('/-', i):
            depth = 1
            out[i:i + 2] = '  '
            i += 2
        elif text.startswith('--', i):
            end = text.find('\n', i)
            end = len(text) if end < 0 else end
            out[i:end] = ' ' * (end - i)
            i = end
        elif text[i] == '"':
            out[i] = ' '
            i += 1
            while i < len(text):
                c = text[i]
                out[i] = '\n' if c == '\n' else ' '
                i += 1
                if c == '\\' and i < len(text):
                    out[i] = ' '
                    i += 1
                elif c == '"':
                    break
        else:
            i += 1
    return ''.join(out)


def module_name(path: str) -> str:
    p = Path(path)
    if p.parts[0] == 'vendor':
        p = Path(*p.parts[1:])
    return '.'.join(p.with_suffix('').parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-index', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'provenance/sources.json').read_text())
    errors: list[str] = []
    files: dict[str, Path] = {}
    lines = ['# Module index', '',
             'Generated by `python3 scripts/check_library.py --write-index`. The README indexes',
             'the principal results; this lists every consolidated source module. Counts include',
             'helper theorem and lemma declarations. They are not a measure of paper coverage.', '',
             'All paths are local to this repository. Source revisions, working-tree status and',
             'integration changes are in [the provenance manifest](../provenance/sources.json).', '']
    for project in manifest['projects']:
        lines += [f"## {project['namespace']}", '', '| Module | Theorems / lemmas |', '|---|---:|']
        for entry in project['files']:
            path = ROOT / entry['path']
            if not path.is_file():
                errors.append(f'Missing source: {entry["path"]}')
                continue
            raw = path.read_bytes()
            actual = hashlib.sha256(raw).hexdigest()
            expected = entry.get('integrated_sha256', entry['source_sha256'])
            if actual != expected:
                errors.append(f'Unrecorded source change: {entry["path"]}')
            if actual != entry['source_sha256'] and not entry.get('changes'):
                errors.append(f'Missing change explanation: {entry["path"]}')
            name = module_name(entry['path'])
            if name in files:
                errors.append(f'Duplicate module: {name}')
            files[name] = path
            code = lean_code(raw.decode())
            count = len(re.findall(r'\b(?:theorem|lemma)\s+', code))
            lines.append(f'| [`{name}`](../{entry["path"]}) | {count} |')
        lines.append('')
    lines += ['## FractalGeometry', '', '| Module | Theorems / lemmas |', '|---|---:|']
    own_paths = [ROOT / 'FractalGeometry.lean', *sorted((ROOT / 'FractalGeometry').rglob('*.lean'))]
    for path in own_paths:
        if path.stem != 'AxCheck':
            relative = str(path.relative_to(ROOT))
            name = module_name(relative)
            files[name] = path
            count = len(re.findall(r'\b(?:theorem|lemma)\s+', lean_code(path.read_text())))
            lines.append(f'| [`{name}`](../{relative}) | {count} |')
    lines.append('')
    imports: dict[str, list[str]] = {}
    for name, path in files.items():
        code = lean_code(path.read_text())
        if re.search(r'\b(?:sorry|admit|axiom|native_decide)\b', code):
            errors.append(f'Proof hole or nonstandard proof primitive: {name}')
        deps = re.findall(r'^(?:public\s+)?(?:meta\s+)?import\s+(.+)$', code, re.M)
        imports[name] = [item for line in deps for item in line.split()]
        for dep in imports[name]:
            if dep.split('.')[0] in {'Challenge', 'Solution'} or dep.endswith('.AxCheck'):
                errors.append(f'Audit/statement-layer import in library: {name} -> {dep}')
            if dep not in files and dep.split('.')[0] not in {
                'Mathlib', 'Lean', 'Init', 'Std', 'Batteries', 'Aesop', 'Qq'}:
                errors.append(f'Unresolved import: {name} -> {dep}')
    reached: set[str] = set()
    active: set[str] = set()

    def visit(name: str) -> None:
        if name in active:
            errors.append(f'Import cycle through {name}')
            return
        if name in reached or name not in files:
            return
        active.add(name)
        for dep in imports[name]:
            visit(dep)
        active.remove(name)
        reached.add(name)

    visit('FractalGeometry.All')
    # The compatibility root is intentionally smaller than All.
    missing = set(files) - reached - {'FractalGeometry'}
    errors.extend(f'Module absent from All: {name}' for name in sorted(missing))
    index = '\n'.join(lines)
    index_path = ROOT / 'docs/modules.md'
    if args.write_index:
        index_path.write_text(index)
    elif not index_path.exists() or index_path.read_text() != index:
        errors.append('Module index is stale; run with --write-index')
    for doc in [ROOT / 'README.md', index_path]:
        if not doc.exists():
            continue
        for target in re.findall(r'\]\(([^)]+)\)', doc.read_text()):
            if '://' in target or target.startswith('#'):
                continue
            target = target.split('#', 1)[0]
            if not (doc.parent / target).exists():
                errors.append(f'Broken link in {doc.name}: {target}')
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    print(f'Checked {len(files)} library modules: provenance, import closure, source hygiene and index.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
